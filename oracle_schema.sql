-- Esquema Oracle para el modulo de prestamos de controles remotos.
-- Ejecutar conectado como ADMCES (o el propietario elegido para la aplicacion).

CREATE TABLE PREST_USUARIOS (
    USUARIO_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    USUARIO VARCHAR2(50 CHAR) NOT NULL,
    NOMBRE VARCHAR2(120 CHAR) NOT NULL,
    CORREO VARCHAR2(254 CHAR),
    ROL VARCHAR2(30 CHAR) DEFAULT 'ENFERMERIA' NOT NULL,
    ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
    FECHA_CREACION TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_PREST_USUARIOS PRIMARY KEY (USUARIO_ID),
    CONSTRAINT UQ_PREST_USUARIOS_USR UNIQUE (USUARIO),
    CONSTRAINT CK_PREST_USUARIOS_ACT CHECK (ACTIVO IN (0, 1))
);

CREATE TABLE PREST_PISOS (
    PISO_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    TORRE VARCHAR2(20 CHAR) NOT NULL,
    CODIGO VARCHAR2(20 CHAR) NOT NULL,
    DESCRIPCION VARCHAR2(100 CHAR),
    ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT PK_PREST_PISOS PRIMARY KEY (PISO_ID),
    CONSTRAINT UQ_PREST_PISOS_COD UNIQUE (TORRE, CODIGO),
    CONSTRAINT CK_PREST_PISOS_ACT CHECK (ACTIVO IN (0, 1))
);

CREATE TABLE PREST_HABITACIONES (
    HABITACION_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    PISO_ID NUMBER NOT NULL,
    CODIGO VARCHAR2(30 CHAR) NOT NULL,
    ACTIVA NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT PK_PREST_HABITACIONES PRIMARY KEY (HABITACION_ID),
    CONSTRAINT UQ_PREST_HAB_COD UNIQUE (PISO_ID, CODIGO),
    CONSTRAINT CK_PREST_HAB_ACT CHECK (ACTIVA IN (0, 1)),
    CONSTRAINT FK_PREST_HAB_PISO FOREIGN KEY (PISO_ID)
        REFERENCES PREST_PISOS (PISO_ID)
);

CREATE TABLE PREST_PACIENTES (
    PACIENTE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    DOCUMENTO VARCHAR2(30 CHAR) NOT NULL,
    NOMBRES VARCHAR2(120 CHAR) NOT NULL,
    APELLIDOS VARCHAR2(120 CHAR) NOT NULL,
    HABITACION_ID NUMBER,
    ESTADO VARCHAR2(20 CHAR) DEFAULT 'HOSPITALIZADO' NOT NULL,
    FECHA_INGRESO TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    FECHA_EGRESO TIMESTAMP,
    CONSTRAINT PK_PREST_PACIENTES PRIMARY KEY (PACIENTE_ID),
    CONSTRAINT UQ_PREST_PAC_DOC UNIQUE (DOCUMENTO),
    CONSTRAINT CK_PREST_PAC_EST CHECK (ESTADO IN ('HOSPITALIZADO', 'EGRESADO', 'TRASLADADO')),
    CONSTRAINT FK_PREST_PAC_HAB FOREIGN KEY (HABITACION_ID)
        REFERENCES PREST_HABITACIONES (HABITACION_ID)
);

CREATE TABLE PREST_CONTROLES (
    CONTROL_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CODIGO VARCHAR2(40 CHAR) NOT NULL,
    MARCA VARCHAR2(40 CHAR) NOT NULL,
    MODELO VARCHAR2(60 CHAR),
    ESTADO VARCHAR2(20 CHAR) DEFAULT 'DISPONIBLE' NOT NULL,
    FECHA_REGISTRO TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    OBSERVACIONES VARCHAR2(500 CHAR),
    CONSTRAINT PK_PREST_CONTROLES PRIMARY KEY (CONTROL_ID),
    CONSTRAINT UQ_PREST_CONTROLES_COD UNIQUE (CODIGO),
    CONSTRAINT CK_PREST_CONTROLES_EST CHECK (ESTADO IN ('DISPONIBLE', 'PRESTADO', 'MANTENIMIENTO', 'BAJA'))
);

CREATE TABLE PREST_PRESTAMOS (
    PRESTAMO_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CONTROL_ID NUMBER NOT NULL,
    PACIENTE_ID NUMBER NOT NULL,
    HABITACION_ID NUMBER NOT NULL,
    USUARIO_ENTREGA_ID NUMBER NOT NULL,
    USUARIO_RECIBE_ID NUMBER,
    FECHA_ENTREGA TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    FECHA_DEVOLUCION TIMESTAMP,
    RECIBE_NOMBRE VARCHAR2(120 CHAR) NOT NULL,
    PARENTESCO VARCHAR2(40 CHAR),
    OBSERVACIONES VARCHAR2(500 CHAR),
    VALOR_TOTAL NUMBER(12, 2) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_PREST_PRESTAMOS PRIMARY KEY (PRESTAMO_ID),
    CONSTRAINT CK_PREST_PREST_FECHAS CHECK (FECHA_DEVOLUCION IS NULL OR FECHA_DEVOLUCION >= FECHA_ENTREGA),
    CONSTRAINT CK_PREST_PREST_VALOR CHECK (VALOR_TOTAL >= 0),
    CONSTRAINT FK_PREST_PREST_CTRL FOREIGN KEY (CONTROL_ID)
        REFERENCES PREST_CONTROLES (CONTROL_ID),
    CONSTRAINT FK_PREST_PREST_PAC FOREIGN KEY (PACIENTE_ID)
        REFERENCES PREST_PACIENTES (PACIENTE_ID),
    CONSTRAINT FK_PREST_PREST_HAB FOREIGN KEY (HABITACION_ID)
        REFERENCES PREST_HABITACIONES (HABITACION_ID),
    CONSTRAINT FK_PREST_PREST_ENT FOREIGN KEY (USUARIO_ENTREGA_ID)
        REFERENCES PREST_USUARIOS (USUARIO_ID),
    CONSTRAINT FK_PREST_PREST_REC FOREIGN KEY (USUARIO_RECIBE_ID)
        REFERENCES PREST_USUARIOS (USUARIO_ID)
);

-- Impide dos prestamos activos simultaneos del mismo control o habitacion.
CREATE UNIQUE INDEX UX_PREST_CTRL_ACTIVO ON PREST_PRESTAMOS (
    CASE WHEN FECHA_DEVOLUCION IS NULL THEN CONTROL_ID END
);
CREATE UNIQUE INDEX UX_PREST_HAB_ACTIVA ON PREST_PRESTAMOS (
    CASE WHEN FECHA_DEVOLUCION IS NULL THEN HABITACION_ID END
);

CREATE INDEX IX_PREST_PAC_HAB ON PREST_PACIENTES (HABITACION_ID);
CREATE INDEX IX_PREST_PREST_PAC ON PREST_PRESTAMOS (PACIENTE_ID, FECHA_ENTREGA);
CREATE INDEX IX_PREST_PREST_HAB ON PREST_PRESTAMOS (HABITACION_ID, FECHA_ENTREGA);
